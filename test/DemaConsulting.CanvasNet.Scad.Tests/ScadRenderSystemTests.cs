    /// <summary>
    ///     Validates that a mirrored solid renders pixel-identical to the same solid written at the mirrored
    ///     position, which also proves the mirrored mesh is wound consistently.
    /// </summary>
    [Fact]
    public void ScadRenderSystem_Mirror_RendersIdenticallyToTheHandPlacedSolid()
    {
        // Arrange
        var mirrored = ScadDocument.Parse("color(\"green\") mirror([1, 0, 0]) translate([10, 0, 0]) cube([3, 3, 3]);");
        var placed = ScadDocument.Parse("color(\"green\") translate([-13, 0, 0]) cube([3, 3, 3]);");
        var view = ScadOrthoView.Top(-11.5, 1.5, 8, 8, 4);

        // Act
        using var fromMirror = view.Render(mirrored);
        using var fromPlacement = view.Render(placed);

        // Assert: identical, and every covered pixel is the green of a front face (not the back-face color)
        AssertSurfacesIdentical(fromPlacement, fromMirror);
        Assert.Equal(144, Count(fromMirror, p => p == Green));
        Assert.Equal(144, Count(fromMirror, p => p != White));

        // The default shaded look is identical too
        var shadedView = ScadOrthoView.Top(-11.5, 1.5, 8, 8, 4);
        using var shadedMirror = shadedView.Render(mirrored, SceneRenderOptions.Default);
        using var shadedPlaced = shadedView.Render(placed, SceneRenderOptions.Default);
        AssertSurfacesIdentical(shadedPlaced, shadedMirror);
    }

