    /// <summary>
    ///     Validates that supersampling antialiases the edges: without it every pixel is a pure color, with it the
    ///     edge pixels blend and their summed coverage tracks the exact polygon area better.
    /// </summary>
    [Fact]
    public void ScadRenderSystem_Supersampling_BlendsEdgePixels()
    {
        // Arrange: the blue cylinder alone, x 32..44 at two pixels per unit
        var view = ScadOrthoView.Top(38, 6, 14, 14, 2);
        var aliased = new SceneRenderOptions { Lights = [new AmbientLight { Intensity = 1.0f }], Supersampling = 1 };
        var smooth = new SceneRenderOptions { Lights = [new AmbientLight { Intensity = 1.0f }], Supersampling = 4 };
        var document = Fixture("primitives");

        // Act
        using var hard = view.Render(document, aliased);
        using var soft = view.Render(document, smooth);

        // Assert: hard edges use only the two pure colors (the sphere and the cube are outside this window)
        Assert.Equal(0, Count(hard, p => p != White && p != Blue));
        var blended = Count(soft, p => p != White && p != Blue);
        Assert.True(blended > 20, $"{blended} blended pixels");

        // The summed coverage (the red channel of blue-on-white falls from 255 to 0 with coverage) estimates the area
        var area = RegularPolygonArea(6, 64) * 4;
        var coverage = 0.0;
        for (var y = 0; y < soft.Height; y++)
        {
            coverage += soft.GetRowSpan(y).ToArray().Sum(p => 1.0 - (p.R / 255.0));
        }

        Assert.InRange(coverage, area * 0.99, area * 1.01);
    }

