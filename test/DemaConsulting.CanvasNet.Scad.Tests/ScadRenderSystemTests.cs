    private static void AssertPegBoard(ScadOrthoView view, Surface surface, int pegs, double pitch)
    {
        // Assert: the base color between the pegs, beyond the first and last peg, and the pegs themselves
        var length = pegs * pitch;
        var left = -pitch / 2;
        var right = length - (pitch / 2);
        Assert.Equal(SteelBlue, At(view, surface, left + 0.5, 0.25));
        Assert.Equal(SteelBlue, At(view, surface, right - 0.75, 0.25));
        Assert.Equal(SteelBlue, At(view, surface, pitch / 2, 4.5));
        Assert.Equal(White, At(view, surface, left - 0.5, 0.25));
        Assert.Equal(White, At(view, surface, right + 0.5, 0.25));
        Assert.Equal(White, At(view, surface, 0.25, 5.5));
        for (var i = 0; i < pegs; i++)
        {
            Assert.Equal(Orange, At(view, surface, (i * pitch) + 0.25, 0.25));
        }

        // The pegs are 32-gons of radius 3 on the base, which is length x 10 below them
        var expectedOrange = pegs * RegularPolygonArea(3, 32) * 4;
        var expectedBase = ((length * 10) - (pegs * RegularPolygonArea(3, 32))) * 4;
        Assert.InRange(Count(surface, p => p == Orange), expectedOrange * 0.96, expectedOrange * 1.04);
        Assert.InRange(Count(surface, p => p == SteelBlue), expectedBase * 0.99, expectedBase * 1.01);
    }

    /// <summary>
    ///     Gets whether a point (relative to the plate center) is covered by the 2D-CSG plate.
    /// </summary>
    /// <param name="x">The X relative to the plate center.</param>
    /// <param name="y">The Y relative to the plate center.</param>
    /// <returns><see langword="true"/> when the plate covers the point.</returns>
    private static bool PlateCovers(double x, double y) =>
        Math.Abs(x) <= 12 && Math.Abs(y) <= 8
        && InRegularPolygon(x, y, 0, 0, 14, 64)
        && !InRegularPolygon(x, y, -6, 0, 3, 32)
        && !(Math.Abs(x - 6) <= 2 && Math.Abs(y) <= 2);

    /// <summary>
    ///     Gets whether the stairs or one of the eight posts of the modules fixture cover a point.
    /// </summary>
    /// <param name="x">The model X.</param>
    /// <param name="y">The model Y.</param>
    /// <returns><see langword="true"/> when the point is covered.</returns>
    private static bool PostsOrStairsCover(double x, double y)
    {
        if (x is > 0 and < 60 && y is > 0 and < 10)
        {
            return true;
        }

        for (var i = 0; i < 8; i++)
        {
            var angle = i * Math.PI / 4;
            if (InRegularPolygon(x, y, -30 + (10 * Math.Cos(angle)), 30 + (10 * Math.Sin(angle)), 2, 24))
            {
                return true;
            }
        }

        return false;
    }

    /// <summary>
    ///     Tests whether a point is inside a polygon (even-odd rule).
    /// </summary>
    /// <param name="x">The point X.</param>
    /// <param name="y">The point Y.</param>
    /// <param name="polygon">The polygon vertices.</param>
    /// <returns><see langword="true"/> when the point is inside.</returns>
    private static bool InPolygon(double x, double y, IReadOnlyList<(double X, double Y)> polygon)
    {
        var inside = false;
        var previous = polygon[^1];
        foreach (var current in polygon)
        {
            if ((current.Y > y) != (previous.Y > y)
                && x < (((previous.X - current.X) * (y - current.Y)) / (previous.Y - current.Y)) + current.X)
            {
                inside = !inside;
            }

            previous = current;
        }

        return inside;
    }

    /// <summary>
    ///     Asserts that an image equals its mirror image.
    /// </summary>
    /// <param name="surface">The image.</param>
    /// <param name="horizontal">Whether to test the left-right mirror.</param>
    /// <param name="vertical">Whether to test the top-bottom mirror.</param>
    private static void AssertMirrorSymmetric(Surface surface, bool horizontal, bool vertical)
    {
        for (var y = 0; y < surface.Height; y++)
        {
            for (var x = 0; x < surface.Width; x++)
            {
                if (horizontal)
                {
                    Assert.Equal(surface[x, y], surface[surface.Width - 1 - x, y]);
                }

                if (vertical)
                {
                    Assert.Equal(surface[x, y], surface[x, surface.Height - 1 - y]);
                }
            }
        }
    }

    /// <summary>
    ///     Gets the bounding rectangle, in pixels, of everything that is not the white background.
    /// </summary>
    /// <param name="surface">The image.</param>
    /// <returns>The first and last covered column and row.</returns>
    private static (int Left, int Right, int Top, int Bottom) CoveredBounds(Surface surface)
    {
        int left = int.MaxValue, right = -1, top = int.MaxValue, bottom = -1;
        for (var y = 0; y < surface.Height; y++)
        {
            if (RowExtent(surface, y, White) is { } extent)
            {
                left = Math.Min(left, extent.First);
                right = Math.Max(right, extent.Last);
                top = Math.Min(top, y);
                bottom = y;
            }
        }

        return (left, right, top, bottom);
    }

    /// <summary>
    ///     Gets whether two images of the same size are equal in every pixel.
    /// </summary>
    /// <param name="a">The first image.</param>
    /// <param name="b">The second image.</param>
    /// <returns><see langword="true"/> when no pixel differs.</returns>
    private static bool AllRowsEqual(Surface a, Surface b)
    {
        for (var y = 0; y < a.Height; y++)
        {
            if (!a.GetRowSpanBytes(y).SequenceEqual(b.GetRowSpanBytes(y)))
            {
                return false;
            }
        }

        return true;
    }
