    /// <summary>
    ///     Validates that the vase's front silhouette equals its profile radius at every height.
    /// </summary>
    [Fact]
    public void ScadRenderSystem_Extrusions_VaseSilhouetteFollowsTheProfile()
    {
        // Arrange: x 70..90, z -2..22 at two pixels per unit
        var view = ScadOrthoView.Front(80, 10, 20, 24, 2);

        // Act
        using var surface = view.Render(Fixture("extrusions"));

        // Assert: radius 8 to z = 2, narrowing to 5 at z = 10, widening to 7 at z = 20
        for (var row = view.Row(19.9); row <= view.Row(0.1); row++)
        {
            var z = view.V(row);
            var radius = z switch
            {
                < 2 => 8.0,
                < 10 => 8.0 - (3.0 * (z - 2.0) / 8.0),
                _ => 5.0 + (2.0 * (z - 10.0) / 10.0),
            };
            var (first, last) = RowExtent(surface, row, White)!.Value;
            Assert.InRange((last - first + 1) / 2.0, (2 * radius) - 1, (2 * radius) + 1);

            // The silhouette is centered on the axis
            Assert.InRange(((first + last + 1) / 2.0 / 2.0) + 70, 79.5, 80.5);
        }
    }

