    /// <summary>
    ///     Validates that a top view of colored primitives shows each solid's exact color over its analytic
    ///     footprint, and the background between them.
    /// </summary>
    [Fact]
    public void ScadRenderSystem_Primitives_TopViewShowsColorsOverAnalyticFootprints()
    {
        // Arrange: one pixel per unit; the cube covers x 0..12, the sphere and the cylinder are radius 6
        var view = ScadOrthoView.Top(22, 6, 44, 14);

        // Act
        using var surface = view.Render(Fixture("primitives"));

        // Assert: colors at the centers and in the gaps
        Assert.Equal(Red, At(view, surface, 6.5, 6.5));
        Assert.Equal(Green, At(view, surface, 22.5, 6.5));
        Assert.Equal(Blue, At(view, surface, 38.5, 6.5));
        Assert.Equal(White, At(view, surface, 15.5, 6.5));
        Assert.Equal(White, At(view, surface, 31.5, 6.5));
        Assert.Equal(White, At(view, surface, 6.5, 12.5));

        // The cube is an exact 12 x 12 block, the cylinder a 64-gon, the sphere a disc up to its tessellation
        var cylinderArea = RegularPolygonArea(6, 64);
        var discArea = Math.PI * 36;
        var red = Count(surface, p => p == Red);
        var green = Count(surface, p => p == Green);
        var blue = Count(surface, p => p == Blue);
        Assert.Equal(144, red);
        Assert.InRange(blue, cylinderArea * 0.95, cylinderArea * 1.05);
        Assert.InRange(green, discArea * 0.9, discArea * 1.03);
        Assert.Equal(red + green + blue, CountNon(surface, White));
    }

