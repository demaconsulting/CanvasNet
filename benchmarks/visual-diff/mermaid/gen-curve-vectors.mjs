// gen-curve-vectors.mjs - records what d3-shape's line generator (the version mermaid bundles) writes for the curves
// mermaid offers for flowchart edges, as the upstream vectors of the CanvasNet.Mermaid edge builder's curve tests.
//
// Developer tooling of benchmarks/visual-diff; see the README there. Usage:
//
//     node gen-curve-vectors.mjs [--modules <folder>] [--out <file>]
//
// <modules> is a folder that holds node_modules/d3-shape (default: the repository root). <out> is the vector file
// (default: test/DemaConsulting.CanvasNet.Mermaid.Tests/Fixtures/upstream-vectors/curves.json). The point sets are
// original; the generator runs d3-shape directly in Node (no browser is needed).

import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// The repository root is three folders above benchmarks/visual-diff/mermaid
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');

// Read the optional arguments
const args = process.argv.slice(2);
let modules = root;
let out = join(root, 'test', 'DemaConsulting.CanvasNet.Mermaid.Tests', 'Fixtures', 'upstream-vectors', 'curves.json');
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--modules' && i + 1 < args.length) {
    modules = resolve(args[++i]);
  } else if (args[i] === '--out' && i + 1 < args.length) {
    out = resolve(args[++i]);
  } else {
    console.error('usage: node gen-curve-vectors.mjs [--modules <folder>] [--out <file>]');
    process.exit(2);
  }
}

const resolver = createRequire(join(modules, 'noop.js'));
const shapeFolder = join(modules, 'node_modules', 'd3-shape');
const shapeVersion = JSON.parse(readFileSync(join(shapeFolder, 'package.json'), 'utf8')).version;
const d3 = await import(pathToFileURL(resolver.resolve('d3-shape')).href);

// The curves of mermaid's insertEdge, by the names its configuration uses
const curves = {
  basis: d3.curveBasis,
  linear: d3.curveLinear,
  natural: d3.curveNatural,
  step: d3.curveStep,
  stepBefore: d3.curveStepBefore,
  stepAfter: d3.curveStepAfter,
  monotoneX: d3.curveMonotoneX,
  monotoneY: d3.curveMonotoneY,
  cardinal: d3.curveCardinal,
  catmullRom: d3.curveCatmullRom,
  bumpX: d3.curveBumpX,
  bumpY: d3.curveBumpY
};

// A small seeded generator, so the random point sets are reproducible
let seed = 20261108;
const random = () => {
  seed = (seed * 1103515245 + 12345) % 2147483648;
  return seed / 2147483648;
};
const randomPoints = (count) =>
  Array.from({ length: count }, (_, i) => [i * 23.7 + random() * 40, random() * 300 - 50]);

const pointSets = {
  one: [[10, 20]],
  two: [[10, 20], [110.5, 60.25]],
  three: [[0, 0], [50, 100], [100, 0]],
  'edge-down': [[81.898, 87], [81.898, 112], [81.898, 137], [81.898, 162], [81.898, 187]],
  'edge-bend': [[83.089, 85.05], [99.138, 68.367], [126.71, 43.342], [152.234, 35]],
  corner: [[0, 0], [0, 50], [5, 55], [60, 55], [60, 120]],
  'x-decreasing': [[300, 10], [200, 40], [100, 20], [0, 90]],
  coincident: [[0, 0], [0, 0], [40, 30], [40, 30], [80, 0]],
  vertical: [[50, 0], [50, 40], [50, 80], [52, 120]],
  'random-6': randomPoints(6),
  'random-9': randomPoints(9),
  'tiny-steps': [[0.0004, 0.0006], [0.0012, 0.0019], [1.0005, 2.4995], [3.33333, 7.77777]]
};

const cases = [];
for (const [curveName, curve] of Object.entries(curves)) {
  for (const [setName, points] of Object.entries(pointSets)) {
    const path = d3.line().curve(curve)(points);
    cases.push({ name: `${curveName}-${setName}`, curve: curveName, points, expected: path });
  }
}

// One case per line keeps the file reviewable and its diffs small
const source = `Generated by benchmarks/visual-diff/mermaid/gen-curve-vectors.mjs from d3-shape ${shapeVersion} (ISC, Mike Bostock); the point sets are original. See src/DemaConsulting.CanvasNet.Mermaid/third-party/README.md.`;
const lines = [];
lines.push('{');
lines.push(`  "source": ${JSON.stringify(source)},`);
lines.push(`  "d3ShapeVersion": ${JSON.stringify(shapeVersion)},`);
lines.push('  "cases": [');
lines.push(cases.map((c) => '    ' + JSON.stringify(c)).join(',\n'));
lines.push('  ]');
lines.push('}');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n') + '\n');
console.log(`d3-shape ${shapeVersion}: wrote ${cases.length} curve vectors to ${out}`);
